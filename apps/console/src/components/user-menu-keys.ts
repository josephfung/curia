/**
 * Where focus moves in the user menu for a key, or null when the key isn't
 * a menu navigation key. Arrows wrap; with nothing focused, Down starts at
 * the top and Up at the bottom.
 */
export function nextMenuIndex(key: string, current: number, count: number): number | null {
  if (count === 0) return null;
  switch (key) {
    case 'ArrowDown':
      return current < 0 ? 0 : (current + 1) % count;
    case 'ArrowUp':
      return current < 0 ? count - 1 : (current - 1 + count) % count;
    case 'Home':
      return 0;
    case 'End':
      return count - 1;
    default:
      return null;
  }
}
