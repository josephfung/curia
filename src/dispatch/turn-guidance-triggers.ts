// turn-guidance-triggers.ts — which trigger guidance an inbound turn gets (#1959).
//
// The dispatcher already decides every one of these triggers while it builds the
// coordinator's agent.task: whether the sender is the principal (liveTurn), whether the
// [ACTIVE OUTBOUND CONTEXT] block went in and what its entries carry, whether this is an
// email and whether Curia was CC'd. This function turns those facts into the keys the
// runtime renders (src/agents/prompts/turn-guidance.ts), so the guidance costs nothing on
// a turn without its trigger.

import type { TurnGuidanceKey } from '../agents/prompts/turn-guidance.js';
import { isTaskWakeReplyBinding } from './task-wake-reply.js';
import type { AcquaintanceEvidence } from '../contacts/principal-acquaintance.js';

export interface InboundGuidanceFacts {
  /** A live principal turn (stampOriginator). */
  liveTurn: boolean;
  /**
   * Metadata of the entries rendered into this turn's [ACTIVE OUTBOUND CONTEXT] block.
   * Empty when no block was injected (no entries, a non-principal turn, or a read failure).
   */
  injectedEntryMetadata: ReadonlyArray<Record<string, unknown> | null>;
  /**
   * Entries rendered into a non-principal sender's block: the messages sent to them (#2261).
   * Absent or zero when no such block was injected.
   */
  recipientEntryCount?: number;
  channelId: string;
  /** Email only: Curia was CC'd rather than addressed directly. */
  curiaCc: boolean;
  /** Non-principal auto-generated mail. Its preamble already says NO_REPLY and when to escalate. */
  autoGeneratedSuppress: boolean;
  /**
   * The principal's message registered at least one sign-in code candidate for a pending
   * sms/app verification (#2017, Dispatcher.trackPrincipalRelayedCodes).
   * Absent means no.
   */
  verificationCodeReceived?: boolean;
  /**
   * The inbound text looks like a spot-check verdict (looksLikeSpotCheckReply). Only
   * honoured on a live principal turn where Curia is not merely CC'd: whether the sender
   * may score anything is decided here, not by the text.
   */
  spotCheckReply: boolean;
  /**
   * Email only: the inbound is a forward (looksLikeForward). Only honoured on a live
   * principal turn addressed to Curia; a forward Curia is CC'd on is to someone else.
   * Absent means no.
   */
  forward?: boolean;
  /** The inbound text holds a booking-page link (hasBookingPageLink). Absent means no. */
  bookingLink?: boolean;
  /**
   * The dispatcher elevated this (non-principal) sender on evidence the principal knows
   * them (#2227). Absent means it did not.
   */
  principalAcquaintance?: AcquaintanceEvidence;
  /**
   * The message's own text (above any quote) asks to make room in the calendar
   * (looksLikeMakeRoom). Only honoured on a live principal turn. Absent means no.
   */
  makeRoom?: boolean;
}

// "Make room" language (#2227): the principal offering to move their own commitments. Plain
// "find some time" is left out: it is how most scheduling requests are phrased, and asks
// for nothing to move.
const MAKE_ROOM_PATTERNS: readonly RegExp[] = [
  /\b(?:move|shift|shuffle|rearrange|juggle)\s+(?:a\s+few\s+|some\s+|a\s+couple\s+(?:of\s+)?)?(?:things|stuff|meetings|commitments)\b/i,
  /\b(?:move|shift|shuffle|rearrange|juggle|clear)\s+(?:my|the)\s+(?:calendar|schedule|diary)\b/i,
  /\bmake\s+(?:some\s+)?(?:room|space)\b/i,
  /\b(?:find|free\s+up|clear|carve\s+out|open\s+up)\s+(?:some\s+)?(?:room|space)\b/i,
  /\b(?:free\s+up|clear|carve\s+out|open\s+up)\s+(?:some\s+)?time\b/i,
  // One of the principal's own blocks by name ("I can move my focus block", "push my 1:1"),
  // the events make-room moves first. Up to two words may name it ("my Thursday focus block").
  /\b(?:move|shift|push|bump|slide)\s+(?:my|our)\s+(?:[\w'-]+\s+){0,2}(?:block|focus\s+time|hold|1:1|one-on-one|1-on-1)(?=\W|$)/i,
];

// A refusal ahead of the match in the same clause: "Don't make room by moving my meetings",
// "I can't move my focus block", "no need to clear my calendar". A clause ends at . ; ! ? , or
// a line break, so "Don't worry, I'll make some room" is still a request.
const MAKE_ROOM_NEGATION = /\b(?:don['’]?t|do\s+not|doesn['’]?t|not|never|no\s+need\s+to|can['’]?t|cannot|won['’]?t|shouldn['’]?t|rather\s+not|without)\b/i;
const CLAUSE_END = /[.;!?,\n]/;

/** Whether the match at `index` has a negation earlier in its clause. */
function negatedInClause(text: string, index: number): boolean {
  let start = index;
  while (start > 0 && !CLAUSE_END.test(text[start - 1]!)) start--;
  return MAKE_ROOM_NEGATION.test(text.slice(start, index));
}

/**
 * Whether the text asks to make room in the calendar ("let me move a few things around").
 * Lines quoted with `>` are someone else's words and are skipped. The email caller has
 * already cut quoted mail; this covers a quote typed or pasted into Signal, Slack or SMS.
 * A refused move ("don't move my meetings, offer another day") is not a request.
 */
export function looksLikeMakeRoom(text: string): boolean {
  const own = text.split('\n').filter((line) => !line.trimStart().startsWith('>')).join('\n');
  return MAKE_ROOM_PATTERNS.some((p) => {
    for (const match of own.matchAll(new RegExp(p.source, `${p.flags}g`))) {
      if (!negatedInClause(own, match.index)) return true;
    }
    return false;
  });
}

// Booking-page hosts (#2227). A link on the host's root is not a booking page, so each needs
// a path. Google's two forms: the calendar.app.google short link and the long
// calendar.google.com/calendar/appointments URL. Microsoft Bookings and Bookings with me
// live under outlook.office(365).com/book and /bookwithme.
const BOOKING_PAGE_URL = new RegExp(
  [
    String.raw`https?://(?:[\w-]+\.)*(?:calendly\.com|cal\.com|savvycal\.com|zcal\.co|tidycal\.com|youcanbook\.me|acuityscheduling\.com|calendar\.app\.google|meetings(?:-[a-z0-9]+)?\.hubspot\.com)/[^\s/]`,
    String.raw`https?://calendar\.google\.com/calendar/(?:u/\d+/)?appointments/`,
    String.raw`https?://outlook\.office(?:365)?\.com/(?:book|bookwithme)/`,
  ].join('|'),
  'i',
);

/** Whether the text holds a link to a scheduling page (Calendly, Google booking pages and similar). */
export function hasBookingPageLink(content: string): boolean {
  return BOOKING_PAGE_URL.test(content);
}

/** Verdicts are short ("2 bad, that was a renewal notice"); a long message is something else. */
const SPOT_CHECK_REPLY_MAX_CHARS = 400;

// A number (optionally "#2") then good/bad at the very start of the message. Anchoring to the
// start is what keeps "I have 2 good ideas" and "Meet at 2" out; a looser "number then
// good/bad anywhere" rule would match both. A digest reply puts its new text first, above
// any quoted digest.
const SPOT_CHECK_REPLY_START = /^#?\d{1,2}\s+(good|bad)\b/i;

/** Whether a principal's message looks like a verdict on a digest spot check. */
export function looksLikeSpotCheckReply(text: string): boolean {
  const trimmed = text.trim();
  return trimmed.length < SPOT_CHECK_REPLY_MAX_CHARS && SPOT_CHECK_REPLY_START.test(trimmed);
}

/** One number-and-verdict pair as the principal typed it ("2 bad"). */
export interface TypedSpotCheckVerdict {
  n: number;
  verdict: 'good' | 'bad';
}

// Every "N good" / "N bad" pair, anywhere in the reply ("1 good 3 good", "1 good, 2 bad").
// The lookbehind keeps the tail of a longer number ("123 good") from reading as "23 good".
const SPOT_CHECK_PAIR = /(?<!\d)(\d{1,2})\s+(good|bad)\b/gi;

/**
 * The number-and-verdict pairs in a spot-check reply, in the order typed, each pair once.
 *
 * SECURITY (F2): the dispatcher stamps these into trusted task metadata, and
 * record-spot-check records only pairs found here. Call it on spotCheckCandidateText, which
 * cuts the text at the first recognised quote or forward marker (firstQuoteLine). Text below
 * such a marker cannot add a pair. Text above it can, whether the principal typed or pasted
 * it, and so can a forward whose marker firstQuoteLine does not recognise; the read-back of
 * what was recorded (SPOT_CHECK_REPLY) is the check on those. A tool result never reaches
 * this text, so it cannot add a pair. Both verdicts for one number are kept if typed
 * ("2 good, no wait 2 bad"); the coordinator still has to pick one, and either is the
 * principal's own.
 */
export function parseSpotCheckVerdicts(text: string): TypedSpotCheckVerdict[] {
  const pairs: TypedSpotCheckVerdict[] = [];
  for (const m of text.matchAll(SPOT_CHECK_PAIR)) {
    const n = Number(m[1]);
    const verdict = m[2]!.toLowerCase() === 'good' ? 'good' : 'bad';
    if (!pairs.some((p) => p.n === n && p.verdict === verdict)) pairs.push({ n, verdict });
  }
  return pairs;
}

// The email channel prepends "Subject: <subject>\n\n" to every body (message-converter.ts),
// which would hide a reply's first words from the start-of-message rule.
const EMAIL_SUBJECT_PREFIX = /^Subject:[^\n]*\n+/;

// Where a mail client starts quoting the message being replied to. A reply on the digest's
// thread quotes the whole digest (several hundred characters, htmlToText keeps it, nothing
// in src/ strips it), which would blow the length gate. Heuristic on purpose. A missed marker
// on a long message only means the guidance does not fire. On a short message (under the
// 400-char gate) the text below a missed marker stays in, and its "N good/bad" pairs are
// stamped as typed (parseSpotCheckVerdicts), so add markers here as mail clients need them.
const QUOTE_HEADER_ON_WROTE = /^On .+ wrote:$/i;
const QUOTE_ORIGINAL_MESSAGE = /^-{2,}\s*Original Message\s*-{2,}$/i;
// The line htmlToText renders for an <hr> (src/channels/email/html-to-text.ts).
const OUTLOOK_HR_RULE = /^-{3,}$/;
// Forward and separator markers. Text below them was written by someone else, so it must not
// reach the length gate or parseSpotCheckVerdicts. Gmail: "---------- Forwarded message
// ---------". Apple Mail: "Begin forwarded message:". Classic Outlook: a line of underscores
// above its From:/Sent: block (ten or more, so a short run in the reply's own text is kept).
const FORWARD_GMAIL = /^-{2,}\s*Forwarded message\s*-{2,}$/i;
const FORWARD_APPLE = /^Begin forwarded message:?$/i;
const SEPARATOR_UNDERSCORES = /^_{10,}$/;

/** Index of the first line that starts quoted or forwarded text, or -1 when there is none. */
function firstQuoteLine(lines: readonly string[]): number {
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i]!.trim();
    if (line.startsWith('>')) return i;
    if (QUOTE_ORIGINAL_MESSAGE.test(line)) return i;
    if (FORWARD_GMAIL.test(line) || FORWARD_APPLE.test(line) || SEPARATOR_UNDERSCORES.test(line)) return i;
    if (QUOTE_HEADER_ON_WROTE.test(line)) return i;
    // Gmail wraps a long "On ... <address> wrote:" header onto a second line.
    if (/^On /i.test(line) && i + 1 < lines.length && QUOTE_HEADER_ON_WROTE.test(`${line} ${lines[i + 1]!.trim()}`)) return i;
    // Outlook-style header block. Only after a blank line or a bare rule line, so a "From:"
    // inside the reply's own sentence-per-line text is not mistaken for one.
    if (/^From:\s/i.test(line) && i > 0) {
      const prev = lines[i - 1]!.trim();
      if (prev === '') return i;
      // Outlook on the web / new Outlook put an <hr> above the header block, which htmlToText
      // renders as a "---" line directly above "From:" (F3). Cut at the rule so it does not
      // dangle on the end of the reply.
      if (OUTLOOK_HR_RULE.test(prev)) return i - 1;
    }
  }
  return -1;
}

/**
 * The text to test with looksLikeSpotCheckReply: the inbound content, minus the email
 * channel's Subject line and, for email, minus the quoted earlier message. The dispatcher
 * has no quote-stripped body, but a reply puts its new text first, so cutting at the first
 * quote marker leaves just the reply for the start-of-message rule and the length gate.
 */
export function spotCheckCandidateText(channelId: string, content: string): string {
  if (channelId !== 'email') return content;
  const lines = content.replace(EMAIL_SUBJECT_PREFIX, '').split('\n');
  const quoteAt = firstQuoteLine(lines);
  return (quoteAt === -1 ? lines : lines.slice(0, quoteAt)).join('\n').trim();
}

// A forward's subject prefix: "Fwd:" (Gmail, Apple Mail), "FW:" (Outlook), "Fw:".
const FORWARD_SUBJECT = /^Subject:\s*(fwd?|fw)\s*:/i;

/**
 * Whether an inbound email is a forward (#2227): a forward subject prefix, or a Gmail or
 * Apple Mail forward marker as the first quote marker. Only the first: a reply whose quoted
 * history holds an older forward is a reply. Not the Outlook underscore separator alone,
 * which replies carry too; an Outlook forward is caught by its "FW:" subject.
 */
export function looksLikeForward(channelId: string, content: string): boolean {
  if (channelId !== 'email') return false;
  if (FORWARD_SUBJECT.test(content)) return true;
  const lines = content.replace(EMAIL_SUBJECT_PREFIX, '').split('\n');
  const quoteAt = firstQuoteLine(lines);
  if (quoteAt === -1) return false;
  const marker = lines[quoteAt]!.trim();
  return FORWARD_GMAIL.test(marker) || FORWARD_APPLE.test(marker);
}

export function inboundTurnGuidance(facts: InboundGuidanceFacts): TurnGuidanceKey[] {
  // Machine mail gets nothing more: reply-shaping and reply mechanics do not apply to a
  // message the coordinator must not answer.
  if (facts.autoGeneratedSuppress) return [];

  const keys: TurnGuidanceKey[] = [];
  const entries = facts.injectedEntryMetadata;
  // Only a live principal turn may record a verdict: a non-principal "2 good" must not score.
  // A message where Curia is only CC'd is written to someone else ("2 good candidates came
  // through"), so it is never a verdict on Curia's digest either (F1).
  const spotCheckVerdict = facts.liveTurn && facts.spotCheckReply && !facts.curiaCc;
  const principalForward = facts.liveTurn && facts.forward === true && facts.channelId === 'email' && !facts.curiaCc;
  if (!facts.liveTurn) {
    keys.push('non-principal-reply-shaped');
    if (facts.principalAcquaintance !== undefined) {
      keys.push(facts.principalAcquaintance === 'principal-domain' ? 'principal-colleague' : 'principal-correspondent');
      keys.push('acquaintance-time-request');
    }
    if ((facts.recipientEntryCount ?? 0) > 0) keys.push('recipient-outbound-context');
  } else if (entries.length === 0) {
    // A spot-check verdict ("2 bad") is reply-shaped but not ambiguous: the reply-shaped note
    // says to ask what the principal is replying to, spot-check-reply says to act. They give
    // conflicting advice, so the verdict key replaces the note. With an outbound block the
    // block's keys stay and spot-check-reply is added alongside them (below). A forward is
    // self-contained and principal-forward says to act, so it replaces the note too.
    if (!spotCheckVerdict && !principalForward) keys.push('principal-reply-shaped');
  }
  if (facts.liveTurn && facts.verificationCodeReceived === true) keys.push('verification-code-received');
  if (principalForward) keys.push('principal-forward');
  if (facts.bookingLink === true) keys.push('booking-link');
  if (facts.liveTurn && facts.makeRoom === true) keys.push('make-room');
  if (facts.liveTurn && entries.length > 0) {
    keys.push('outbound-context');
    if (entries.some((m) => isTaskWakeReplyBinding(m))) keys.push('outbound-context-task-wake');
    if (entries.some((m) => typeof m?.['resume_token'] === 'string' && m['resume_token'] !== '')) {
      keys.push('outbound-context-clarification');
    }
    // Meeting-debrief prompts carry the meeting title as `subject` (agents/meeting-debrief.yaml).
    if (entries.some((m) => typeof m?.['subject'] === 'string' && m['subject'].trim() !== '')) {
      keys.push('outbound-context-debrief');
    }
  }

  if (spotCheckVerdict) keys.push('spot-check-reply');

  if (facts.channelId === 'email') {
    if (facts.curiaCc) {
      if (facts.liveTurn) keys.push('email-cc-principal');
      keys.push('email-cc-reply');
    } else {
      keys.push('email-direct-reply');
    }
    keys.push('email-etiquette');
  }
  return keys;
}
