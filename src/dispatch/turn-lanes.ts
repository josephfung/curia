// Turn lanes (#2018, ADR-053). One in-process owner of "who is running on conversation X".
//
// The class has no database and no bus. With `enabled: false` every method is a no-op and
// nothing is retained, so turns stay concurrent, as they did before #2018. With the flag on, a
// coordinator turn on a human channel holds the conversation until it releases. A live
// follow-up may join that turn only when tryInject's checks all pass; everything else waits
// its own turn.
//
// Contact boundary. Injection compares contact UUIDs, not display names, channel sender
// ids, or the principal flag. Both sides must be UUID-shaped (a raw email, phone number, or
// the 'unresolved' sentinel never matches), the holder must have been stamped from a
// resolved contact, and the follow-up must carry an explicit admission that it was resolved,
// not auto-generated, and clean of injection-scanner findings. A missing or mistyped
// admission fails closed. The queued record is a frozen copy, so a caller cannot retarget
// the sender after the check.
//
// Single process. The map lives in this process. ADR-051's instance lock is advisory at
// boot (a second Curia continues without it), so it does not extend this lock across
// processes. A second process would need a Postgres advisory lock; that is out of scope.
//
// tryInject, closeIfIdle, takeQueued, confirmDrained, release, and cancelReservation are
// synchronous. No await may be inserted between their check and their state change:
// handleInbound and the tool loop interleave only at await points, and the reservation has
// to be visible to the next arrival before this call returns.

import type { AgentTaskEvent, AgentTaskPayload, InjectionDrainPoint } from '../bus/events.js';
import { isDelegatedSpecialistTask, parseTaskOriginator } from '../agents/delegated-task-context.js';
import type { Logger } from '../logger.js';
import { isUuid } from '../util/uuid.js';

/** Channels whose coordinator tasks are not conversation turns. Voice never publishes one. */
const UNLANED_CHANNELS: ReadonlySet<string> = new Set(['scheduler', 'internal', 'bullpen', 'voice']);

const COORDINATOR_AGENT_ID = 'coordinator';

/** How much of a display field may be stored. The message body is not passed through this. */
const LABEL_MAX = 80;
const CHANNEL_MAX = 64;
const RECEIVED_AT_MAX = 40;

export interface LaneHolder {
  taskEventId: string;
  conversationId: string;
  /** metadata.originator.contactId. Null when the turn has no originator. */
  originatorContactId: string | null;
  /**
   * True only when `originatorContactId` is the contact UUID of a resolved contact.
   * An unresolved stamp stores the raw channel sender id in that field; those turns
   * are laned (others wait) but nothing may inject into them.
   */
  originatorResolved: boolean;
  originatorIsPrincipal: boolean;
  liveTurn: boolean;
  synthetic: boolean;
}

export interface InjectableInput {
  inboundEventId: string;
  senderContactId: string;
  /**
   * True only when contact resolution bound `senderContactId` to this message.
   * Anything else fails closed, including a missing field at runtime.
   */
  senderResolved: boolean;
  /** True for auto-generated mail. Those wait for their own turn. */
  autoGenerated: boolean;
  /**
   * Injection-scanner finding count. Zero is the only value that may inject.
   * A missing or non-integer count fails closed.
   */
  injectionFindingCount: number;
  senderLabel?: string;
  channelId: string;
  liveTurn: boolean;
  /** taskContent after the full handleInbound pipeline (preambles, CC block, etc.) */
  content: string;
  /** Raw message text, for working memory (mirrors originalContent at the runtime). */
  originalContent: string;
  turnGuidance?: AgentTaskPayload['turnGuidance'];
  receivedAt: string;
}

export type TicketResult =
  | { kind: 'drained'; hostTaskEventId: string }
  | { kind: 'returned'; reason: 'holder_ended' };

export type TryInjectResult =
  | { kind: 'queued'; ticket: Promise<TicketResult> }
  | { kind: 'not_injected'; reason: 'disabled' | 'no_holder' | 'closing' | 'ineligible' | 'cap' };

export interface LaneGrant {
  waitedMs: number;
  timedOut: boolean;
}

interface Queued {
  input: InjectableInput;
  ticket: Promise<TicketResult>;
  resolve: (result: TicketResult) => void;
  settled: boolean;
  /** Set once working memory has the row. Release must not hand this ticket back. */
  persisted: boolean;
  audit?: RetainedFollowUp['audit'];
}

/** A stored follow-up whose audit publish has not succeeded yet. */
export interface RetainedFollowUp {
  hostTaskEventId: string;
  input: InjectableInput;
  audit: {
    conversationId: string;
    agentId: string;
    drainPoint: InjectionDrainPoint;
  };
}

interface Waiter {
  holder: LaneHolder;
  enqueuedAt: number;
  grant: Promise<LaneGrant>;
  resolve: (grant: LaneGrant) => void;
  settled: boolean;
  /** True once acquire() has been asked for this task, including while it is still waiting. */
  acquireRequested: boolean;
  timer: ReturnType<typeof setTimeout>;
}

interface Lane {
  holder: LaneHolder | null;
  phase: 'idle' | 'reserved' | 'running' | 'closing';
  /** Follow-ups accepted onto this hold (queued or already drained). The cap counts these. */
  accepted: number;
  queue: Queued[];
  /** Taken by the runtime and not yet confirmed or returned. */
  pending: Map<string, Queued>;
  drainedIds: Set<string>;
  waiters: Waiter[];
  inputAbort: AbortController;
}

interface Intake {
  waiters: Array<() => void>;
}

export interface TurnLanesOptions {
  enabled: boolean;
  maxInjectionsPerTurn: number;
  /** Extra tool-loop rounds granted per drained follow-up. The runtime reads this. */
  extraRoundsPerInjection: number;
  laneWaitTimeoutMs: number;
  logger: Logger;
}

const IMMEDIATE: LaneGrant = Object.freeze({ waitedMs: 0, timedOut: false });

/**
 * Build the holder stamp for a task.
 *
 * `admission` is set only by the dispatcher, which saw the contact resolver.
 * That stamp is taken at reserve and a later acquire of the same task does not
 * replace it. Synthetic publishers never reserve. Their copied originator is
 * treated as resolved only when it cannot be the unresolved branch: a UUID
 * contact id, plus a system role or a tier of known, trusted, or principal.
 * An unresolved stamp stores the raw sender id, a null role, and tier unknown.
 * A Signal ACI is a UUID and still fails that check.
 */
export function holderFromAgentTask(
  task: AgentTaskEvent,
  admission?: { originatorResolved: boolean },
): LaneHolder {
  const originator = parseTaskOriginator(task.payload.metadata?.['originator']);
  const contactId = originator?.contactId ?? null;
  const role = originator?.systemRole;
  const tier = originator?.tier;
  const trustedRole = role === 'principal' || role === 'agent' || role === 'system';
  const resolvedTier = tier === 'known' || tier === 'trusted' || tier === 'principal';
  const inferred = isUuid(contactId) && (trustedRole || resolvedTier);
  const originatorResolved = admission
    ? admission.originatorResolved === true && isUuid(contactId)
    : inferred;
  return {
    taskEventId: task.id,
    conversationId: task.payload.conversationId,
    originatorContactId: contactId,
    originatorResolved,
    originatorIsPrincipal: role === 'principal',
    liveTurn: task.payload.liveTurn === true,
    synthetic: task.payload.syntheticTurn === true,
  };
}

/**
 * Returns a bounded string for the framing line. Newlines and other
 * control characters would let a display name break out of that line. The
 * message body is not passed through here.
 */
function singleLine(value: string, max: number): string {
  const flat = value
    .replace(/[\r\n\u2028\u2029]+/g, ' ')
    .replace(/[\u0000-\u001F\u007F]/g, '')
    .trim();
  return flat.length <= max ? flat : flat.slice(0, max);
}

function copyHolder(holder: LaneHolder): LaneHolder {
  return Object.freeze({
    taskEventId: holder.taskEventId,
    conversationId: holder.conversationId,
    originatorContactId: holder.originatorContactId,
    originatorResolved: holder.originatorResolved === true,
    originatorIsPrincipal: holder.originatorIsPrincipal === true,
    liveTurn: holder.liveTurn === true,
    synthetic: holder.synthetic === true,
  });
}

function copyInput(input: InjectableInput): InjectableInput {
  const copy: InjectableInput = {
    inboundEventId: input.inboundEventId,
    senderContactId: input.senderContactId,
    senderResolved: input.senderResolved === true,
    autoGenerated: input.autoGenerated === true,
    injectionFindingCount: input.injectionFindingCount,
    channelId: singleLine(typeof input.channelId === 'string' ? input.channelId : '', CHANNEL_MAX),
    liveTurn: input.liveTurn === true,
    content: typeof input.content === 'string' ? input.content : '',
    originalContent: typeof input.originalContent === 'string' ? input.originalContent : '',
    receivedAt: singleLine(typeof input.receivedAt === 'string' ? input.receivedAt : '', RECEIVED_AT_MAX),
  };
  if (typeof input.senderLabel === 'string') {
    copy.senderLabel = singleLine(input.senderLabel, LABEL_MAX);
  }
  // A new array, not the caller's. Not frozen: the field type is a mutable list
  // of string keys, and the copy no longer aliases the input.
  if (Array.isArray(input.turnGuidance)) {
    copy.turnGuidance = [...input.turnGuidance];
  }
  return Object.freeze(copy);
}

function blankLane(): Lane {
  return {
    holder: null,
    phase: 'idle',
    accepted: 0,
    queue: [],
    pending: new Map(),
    drainedIds: new Set(),
    waiters: [],
    inputAbort: new AbortController(),
  };
}

function deferred<T>(): { promise: Promise<T>; resolve: (value: T) => void } {
  let resolve: (value: T) => void = () => {};
  const promise = new Promise<T>((res) => {
    resolve = res;
  });
  return { promise, resolve };
}

/**
 * Per-conversation turn lane. See the file header for the contact boundary.
 * Constructed once at boot and shared by the dispatcher, the runtime, and the
 * email adapter.
 */
export class TurnLanes {
  readonly enabled: boolean;
  /** Cap on follow-ups accepted onto one hold. The runtime sizes maxRounds from this. */
  readonly maxInjectionsPerTurn: number;
  /** Added to the turn budget once per drained follow-up. */
  readonly extraRoundsPerInjection: number;
  private readonly laneWaitTimeoutMs: number;
  private readonly logger: Logger;
  private readonly lanes = new Map<string, Lane>();
  /** Inbounds the dispatcher has not decided yet. Removed once marked. */
  private readonly intake = new Map<string, Intake>();
  /**
   * Decided inbounds, oldest first. A late intakeSettled still resolves while the id
   * is here. Capped so a long-lived process does not keep every id forever; an id
   * that ages out was decided long before the email adapter is still waiting.
   */
  private readonly settledIntake: string[] = [];
  private readonly settledIntakeIds = new Set<string>();
  private readonly drainedListeners: Array<(hostTaskEventId: string, input: InjectableInput) => void> = [];
  /**
   * Stored, not yet audited. Survives release so the ticket stays unresolved
   * until the audit publish succeeds. A fresh task must not persist the row again.
   */
  private readonly retained: Array<{ hostTaskEventId: string; item: Queued }> = [];
  /** Never aborted. Returned when this task does not hold a lane. */
  private readonly idleSignal = new AbortController().signal;

  constructor(opts: TurnLanesOptions) {
    if (typeof opts.enabled !== 'boolean') {
      throw new Error(`turn lanes: enabled must be a boolean, got: ${typeof opts.enabled}`);
    }
    if (!Number.isInteger(opts.maxInjectionsPerTurn) || opts.maxInjectionsPerTurn <= 0) {
      throw new Error(`turn lanes: maxInjectionsPerTurn must be a positive integer, got: ${opts.maxInjectionsPerTurn}`);
    }
    if (!Number.isInteger(opts.extraRoundsPerInjection) || opts.extraRoundsPerInjection <= 0) {
      throw new Error(`turn lanes: extraRoundsPerInjection must be a positive integer, got: ${opts.extraRoundsPerInjection}`);
    }
    if (!Number.isInteger(opts.laneWaitTimeoutMs) || opts.laneWaitTimeoutMs <= 0) {
      throw new Error(`turn lanes: laneWaitTimeoutMs must be a positive integer, got: ${opts.laneWaitTimeoutMs}`);
    }
    this.enabled = opts.enabled;
    this.maxInjectionsPerTurn = opts.maxInjectionsPerTurn;
    this.extraRoundsPerInjection = opts.extraRoundsPerInjection;
    this.laneWaitTimeoutMs = opts.laneWaitTimeoutMs;
    this.logger = opts.logger;
  }

  /**
   * Coordinator tasks that are not delegated specialist work, on a human channel.
   * Scheduler, internal, bullpen, and voice are never laned. Disabled lanes lane nothing.
   */
  isLaned(task: AgentTaskPayload): boolean {
    if (!this.enabled) return false;
    if (task.agentId !== COORDINATOR_AGENT_ID) return false;
    if (typeof task.conversationId !== 'string' || task.conversationId.length === 0) return false;
    if (UNLANED_CHANNELS.has(task.channelId)) return false;
    if (isDelegatedSpecialistTask(task.metadata)) return false;
    return true;
  }

  /**
   * Dispatcher: synchronous reservation at task creation. Already resolved when
   * the lane was free. The runtime's acquire for the same task id does not wait again.
   */
  reserve(holder: LaneHolder): Promise<LaneGrant> {
    if (!this.enabled) return Promise.resolve(IMMEDIATE);
    return this.join(holder, false);
  }

  /**
   * Runtime: idempotent when this task already holds or is waiting for the lane.
   * Otherwise joins the FIFO. Fails open after laneWaitTimeoutMs without taking
   * the lane from the hung holder.
   */
  acquire(holder: LaneHolder): Promise<LaneGrant> {
    if (!this.enabled) return Promise.resolve(IMMEDIATE);
    return this.join(holder, true);
  }

  /**
   * Dispatcher: synchronous check-and-enqueue. On `queued`, the caller awaits the
   * ticket. Every other result means "create your own task", which then waits in
   * the lane. A reserved holder counts as holding: a follow-up that arrives after
   * reservation and before the first model call joins the turn.
   */
  tryInject(conversationId: string, input: InjectableInput): TryInjectResult {
    if (!this.enabled) return { kind: 'not_injected', reason: 'disabled' };
    return this.enqueue(conversationId, input);
  }

  private enqueue(conversationId: string, input: InjectableInput): TryInjectResult {
    const snap = copyInput(input);
    const lane = this.lanes.get(conversationId);
    if (!lane || !lane.holder || lane.phase === 'idle') {
      return { kind: 'not_injected', reason: 'no_holder' };
    }
    const holder = lane.holder;

    // Same inbound id is the same message. Return the ticket already issued and
    // ignore the new payload, so a second call cannot retarget the sender.
    const existing = this.findQueued(lane, snap.inboundEventId);
    if (existing) return { kind: 'queued', ticket: existing.ticket };
    if (lane.drainedIds.has(snap.inboundEventId)) {
      return {
        kind: 'queued',
        ticket: Promise.resolve({ kind: 'drained', hostTaskEventId: holder.taskEventId }),
      };
    }

    if (lane.phase === 'closing') return { kind: 'not_injected', reason: 'closing' };
    if (!this.eligible(holder, snap)) {
      return { kind: 'not_injected', reason: 'ineligible' };
    }
    if (lane.accepted >= this.maxInjectionsPerTurn) {
      return { kind: 'not_injected', reason: 'cap' };
    }

    const queued = this.makeQueued(snap);
    lane.queue.push(queued);
    lane.accepted += 1;
    this.abortInput(lane);
    this.logger.info(
      {
        conversationId,
        hostTaskEventId: lane.holder.taskEventId,
        inboundEventId: queued.input.inboundEventId,
        senderContactId: queued.input.senderContactId,
      },
      'turn-lanes: follow-up queued',
    );
    return { kind: 'queued', ticket: queued.ticket };
  }

  /**
   * Runtime: take queued input. Tickets stay pending until confirmDrained or release.
   * A non-empty take replaces the input abort controller. Listeners that already
   * hold the aborted signal stay aborted; the next `inputSignal()` is open until
   * another follow-up is queued. An empty take leaves the controller alone, so a
   * delegate already waiting on it still hears the next enqueue.
   */
  takeQueued(taskEventId: string): InjectableInput[] {
    if (!this.enabled) return [];
    const lane = this.laneHeldBy(taskEventId);
    if (!lane) return [];
    const taken = lane.queue.splice(0, lane.queue.length);
    const inputs: InjectableInput[] = [];
    for (const item of taken) {
      lane.pending.set(item.input.inboundEventId, item);
      inputs.push(item.input);
    }
    if (taken.length > 0) lane.inputAbort = new AbortController();
    return inputs;
  }

  /**
   * Runtime: after persistence and the audit event. Resolves those tickets as
   * drained and then notifies listeners. A listener error does not un-resolve
   * the ticket or skip the rest.
   */
  confirmDrained(taskEventId: string, inboundEventIds: string[]): void {
    if (!this.enabled) return;
    const drained: InjectableInput[] = [];
    const lane = this.laneHeldBy(taskEventId);
    if (!lane || !lane.holder) return;
    for (const id of inboundEventIds) {
      const item = this.takePending(lane, id);
      if (!item || item.settled) continue;
      item.settled = true;
      lane.drainedIds.add(id);
      item.resolve({ kind: 'drained', hostTaskEventId: taskEventId });
      drained.push(item.input);
    }
    // Notify after the tickets resolve. A listener may call back into the lane.
    for (const item of drained) this.emitDrained(taskEventId, item);
  }

  /**
   * Runtime, synchronous. Empty queue → mark closing and return true, so a
   * later arrival is `closing` and runs as the next turn. A non-empty queue
   * returns false and leaves the phase alone. A task that does not hold the
   * lane returns true: there is nothing for it to drain.
   */
  closeIfIdle(taskEventId: string): boolean {
    if (!this.enabled) return true;
    const lane = this.laneHeldBy(taskEventId);
    if (!lane) return true;
    if (lane.queue.length > 0) return false;
    lane.phase = 'closing';
    return true;
  }

  /**
   * Idempotent. Marks the hold closed, resolves inputs that were never
   * persisted as `holder_ended`, and grants the next waiter. A follow-up
   * already stored in working memory stays unresolved for an audit retry.
   * A task that does not hold the lane (including one that fail-opened) is a
   * no-op, so it cannot release someone else's turn.
   */
  release(taskEventId: string): void {
    if (!this.enabled) return;
    const found = this.findHeld(taskEventId);
    if (!found) return;
    const { conversationId, lane } = found;
    const undrained = [...lane.queue, ...lane.pending.values()];
    lane.queue = [];
    lane.pending.clear();
    for (const item of undrained) {
      if (item.settled) continue;
      if (item.persisted && item.audit) {
        this.retained.push({ hostTaskEventId: taskEventId, item });
        continue;
      }
      item.settled = true;
      item.resolve({ kind: 'returned', reason: 'holder_ended' });
    }
    const releasedId = lane.holder?.taskEventId;
    lane.holder = null;
    lane.phase = 'idle';
    lane.accepted = 0;
    lane.drainedIds.clear();
    lane.inputAbort = new AbortController();
    this.logger.debug({ conversationId, taskEventId: releasedId }, 'turn-lanes: released');
    this.grantNext(conversationId, lane);
    if (!lane.holder && lane.waiters.length === 0) this.lanes.delete(conversationId);
  }

  /**
   * Runtime: working memory accepted this follow-up and the audit event has
   * not been published yet. Release will park the ticket instead of returning it.
   */
  deferAudit(taskEventId: string, inboundEventId: string, audit: RetainedFollowUp['audit']): void {
    if (!this.enabled) return;
    const item = this.laneHeldBy(taskEventId)?.pending.get(inboundEventId);
    if (!item || item.settled) return;
    item.persisted = true;
    item.audit = audit;
  }

  /**
   * Publish the audit for follow-ups parked by release. Resolves each ticket
   * as drained only after `publish` succeeds. A failure puts that item back
   * and leaves its ticket unresolved.
   */
  async flushRetained(publish: (retained: RetainedFollowUp) => Promise<void>): Promise<void> {
    if (!this.enabled) return;
    const batch = this.retained.splice(0, this.retained.length);
    for (const entry of batch) {
      if (entry.item.settled) continue;
      if (!entry.item.audit) {
        this.retained.push(entry);
        this.logger.error(
          { hostTaskEventId: entry.hostTaskEventId, inboundEventId: entry.item.input.inboundEventId },
          'turn-lanes: retained follow-up is missing its audit record',
        );
        continue;
      }
      const retained: RetainedFollowUp = {
        hostTaskEventId: entry.hostTaskEventId,
        input: entry.item.input,
        audit: entry.item.audit,
      };
      try {
        await publish(retained);
      } catch (err) {
        this.retained.push(entry);
        this.logger.error(
          {
            err,
            hostTaskEventId: retained.hostTaskEventId,
            inboundEventId: retained.input.inboundEventId,
          },
          'turn-lanes: retained follow-up audit retry failed',
        );
        continue;
      }
      entry.item.settled = true;
      entry.item.resolve({ kind: 'drained', hostTaskEventId: entry.hostTaskEventId });
    }
  }

  /**
   * Dispatcher: this task's publish failed before the runtime started, so the id
   * will never acquire or release. Drop a queued waiter without granting it.
   * The current holder is left alone — release() covers that case. Idempotent.
   * Resolves the grant as timed out so the floating reserve() promise settles
   * and a later reader does not treat the cancel as a grant.
   */
  cancelReservation(taskEventId: string): void {
    if (!this.enabled) return;
    const found = this.findWaiting(taskEventId);
    if (!found || found.waiter.settled) return;
    const { conversationId, lane, waiter } = found;
    const index = lane.waiters.indexOf(waiter);
    if (index >= 0) lane.waiters.splice(index, 1);
    globalThis.clearTimeout(waiter.timer);
    waiter.settled = true;
    const waitedMs = Date.now() - waiter.enqueuedAt;
    this.logger.debug(
      { conversationId, taskEventId: waiter.holder.taskEventId, waitedMs },
      'turn-lanes: reservation cancelled',
    );
    waiter.resolve({ waitedMs, timedOut: true });
    if (!lane.holder && lane.waiters.length === 0) this.lanes.delete(conversationId);
  }

  /**
   * Aborts when a follow-up is queued on this holder. Taking that input
   * replaces the controller, so this means "something is queued now", not
   * "something was queued earlier in the turn". A signal already handed out
   * stays aborted. Call after acquire: a signal taken before this task holds
   * the lane never aborts. An unknown task gets a signal that stays open.
   */
  inputSignal(taskEventId: string): AbortSignal {
    if (!this.enabled) return this.idleSignal;
    const lane = this.laneHeldBy(taskEventId);
    return lane ? lane.inputAbort.signal : this.idleSignal;
  }

  /** Email adapter: resolves once the dispatcher has decided what to do with this inbound. */
  intakeSettled(inboundEventId: string): Promise<void> {
    if (!this.enabled) return Promise.resolve();
    if (this.settledIntakeIds.has(inboundEventId)) return Promise.resolve();
    const existing = this.intake.get(inboundEventId);
    const entry = existing ?? { waiters: [] };
    if (!existing) this.intake.set(inboundEventId, entry);
    return new Promise<void>((resolve) => {
      if (this.settledIntakeIds.has(inboundEventId)) resolve();
      else entry.waiters.push(resolve);
    });
  }

  /** Idempotent. Resolves every waiter, including one that arrives afterwards. */
  markIntakeSettled(inboundEventId: string): void {
    if (!this.enabled) return;
    const entry = this.intake.get(inboundEventId);
    const waiters = entry?.waiters.splice(0, entry.waiters.length) ?? [];
    this.intake.delete(inboundEventId);
    this.rememberIntake(inboundEventId);
    for (const resolve of waiters) resolve();
  }

  onDrained(listener: (hostTaskEventId: string, input: InjectableInput) => void): void {
    this.drainedListeners.push(listener);
  }

  /**
   * Same contact, both resolved, neither side auto-generated or scanner-flagged.
   * The principal flag is not an input: a principal does not ride someone else's turn.
   */
  private eligible(holder: LaneHolder, input: InjectableInput): boolean {
    if (holder.originatorResolved !== true) return false;
    if (input.senderResolved !== true) return false;
    if (input.autoGenerated !== false) return false;
    if (typeof input.injectionFindingCount !== 'number' || !Number.isInteger(input.injectionFindingCount) || input.injectionFindingCount !== 0) {
      return false;
    }
    if (!isUuid(holder.originatorContactId) || !isUuid(input.senderContactId)) return false;
    return input.senderContactId === holder.originatorContactId;
  }

  private join(holder: LaneHolder, acquire: boolean): Promise<LaneGrant> {
    // Copy the stamp once; later reads use the copy.
    const stamped = copyHolder(holder);
    if (stamped.taskEventId.length === 0 || stamped.conversationId.length === 0) {
      this.logger.warn(
        { taskEventId: stamped.taskEventId, conversationId: stamped.conversationId },
        'turn-lanes: refusing to lane a task with an empty id',
      );
      return Promise.resolve(IMMEDIATE);
    }

    const alreadyHeld = this.findHeld(stamped.taskEventId);
    if (alreadyHeld) {
      this.noteHolderMismatch(alreadyHeld.lane.holder, stamped);
      if (acquire && alreadyHeld.lane.phase === 'reserved') alreadyHeld.lane.phase = 'running';
      this.logger.debug(
        { conversationId: alreadyHeld.conversationId, taskEventId: stamped.taskEventId },
        acquire ? 'turn-lanes: acquired' : 'turn-lanes: reserved',
      );
      return Promise.resolve(IMMEDIATE);
    }

    const waiting = this.findWaiting(stamped.taskEventId);
    if (waiting) {
      if (acquire) waiting.waiter.acquireRequested = true;
      this.noteHolderMismatch(waiting.waiter.holder, stamped);
      return waiting.waiter.grant;
    }

    const lane = this.lanes.get(stamped.conversationId) ?? blankLane();
    if (!this.lanes.has(stamped.conversationId)) this.lanes.set(stamped.conversationId, lane);

    if (!lane.holder || lane.phase === 'idle') {
      this.beginHold(lane, stamped, acquire ? 'running' : 'reserved');
      this.logger.debug(
        { conversationId: stamped.conversationId, taskEventId: stamped.taskEventId },
        acquire ? 'turn-lanes: acquired' : 'turn-lanes: reserved',
      );
      return Promise.resolve(IMMEDIATE);
    }

    const waiter = this.makeWaiter(stamped, acquire);
    lane.waiters.push(waiter);
    this.logger.debug(
      {
        conversationId: stamped.conversationId,
        taskEventId: stamped.taskEventId,
        holderTaskEventId: lane.holder.taskEventId,
      },
      'turn-lanes: waiting',
    );
    return waiter.grant;
  }

  private beginHold(lane: Lane, holder: LaneHolder, phase: 'reserved' | 'running'): void {
    lane.holder = copyHolder(holder);
    lane.phase = phase;
    lane.accepted = 0;
    lane.queue = [];
    lane.pending = new Map();
    lane.drainedIds = new Set();
    lane.inputAbort = new AbortController();
  }

  private makeWaiter(holder: LaneHolder, acquire: boolean): Waiter {
    const { promise, resolve } = deferred<LaneGrant>();
    const enqueuedAt = Date.now();
    const stamped = copyHolder(holder);
    // Capture the string. The arrow must not read the caller's object later.
    const conversationId = stamped.conversationId;
    const waiter: Waiter = {
      holder: stamped,
      enqueuedAt,
      grant: promise,
      resolve,
      settled: false,
      acquireRequested: acquire,
      timer: globalThis.setTimeout(() => this.failOpen(conversationId, waiter), this.laneWaitTimeoutMs),
    };
    return waiter;
  }

  private failOpen(conversationId: string, waiter: Waiter): void {
    if (waiter.settled) return;
    const lane = this.lanes.get(conversationId);
    if (!lane) return;
    const index = lane.waiters.indexOf(waiter);
    if (index < 0) return;
    lane.waiters.splice(index, 1);
    waiter.settled = true;
    const waitedMs = Date.now() - waiter.enqueuedAt;
    this.logger.error(
      {
        conversationId,
        holderTaskEventId: lane.holder?.taskEventId ?? null,
        waitedMs,
        taskEventId: waiter.holder.taskEventId,
      },
      'turn-lanes: wait timed out — running anyway',
    );
    waiter.resolve({ waitedMs, timedOut: true });
    if (!lane.holder && lane.waiters.length === 0) this.lanes.delete(conversationId);
  }

  private grantNext(conversationId: string, lane: Lane): void {
    while (lane.waiters.length > 0) {
      const waiter = lane.waiters.shift();
      if (!waiter || waiter.settled) continue;
      globalThis.clearTimeout(waiter.timer);
      waiter.settled = true;
      const phase = waiter.acquireRequested ? 'running' : 'reserved';
      this.beginHold(lane, waiter.holder, phase);
      const waitedMs = Date.now() - waiter.enqueuedAt;
      this.logger.debug(
        { conversationId, taskEventId: waiter.holder.taskEventId, waitedMs },
        'turn-lanes: acquired',
      );
      waiter.resolve({ waitedMs, timedOut: false });
      return;
    }
  }

  private makeQueued(input: InjectableInput): Queued {
    const { promise, resolve } = deferred<TicketResult>();
    return { input, ticket: promise, resolve, settled: false, persisted: false };
  }

  private findQueued(lane: Lane, inboundEventId: string): Queued | undefined {
    return lane.queue.find((item) => item.input.inboundEventId === inboundEventId)
      ?? lane.pending.get(inboundEventId);
  }

  private takePending(lane: Lane, inboundEventId: string): Queued | undefined {
    const pending = lane.pending.get(inboundEventId);
    if (pending) {
      lane.pending.delete(inboundEventId);
      return pending;
    }
    const index = lane.queue.findIndex((item) => item.input.inboundEventId === inboundEventId);
    if (index < 0) return undefined;
    const [item] = lane.queue.splice(index, 1);
    return item;
  }

  private abortInput(lane: Lane): void {
    if (!lane.inputAbort.signal.aborted) lane.inputAbort.abort();
  }

  private emitDrained(hostTaskEventId: string, input: InjectableInput): void {
    for (const listener of this.drainedListeners) {
      try {
        listener(hostTaskEventId, input);
      } catch (err) {
        this.logger.error(
          { err, hostTaskEventId, inboundEventId: input.inboundEventId },
          'turn-lanes: onDrained listener failed',
        );
      }
    }
  }

  private rememberIntake(inboundEventId: string): void {
    if (this.settledIntakeIds.has(inboundEventId)) return;
    this.settledIntakeIds.add(inboundEventId);
    this.settledIntake.push(inboundEventId);
    const overflow = this.settledIntake.length - 10_000;
    for (let i = 0; i < overflow; i += 1) {
      const oldest = this.settledIntake.shift();
      if (oldest) this.settledIntakeIds.delete(oldest);
    }
  }

  private noteHolderMismatch(current: LaneHolder | null, next: LaneHolder): void {
    if (!current) return;
    const sameContact = current.originatorContactId === next.originatorContactId
      && current.originatorResolved === (next.originatorResolved === true);
    const sameConversation = current.conversationId === next.conversationId;
    if (sameContact && sameConversation) return;
    // Keep the first stamp. A later call must not widen who may inject.
    this.logger.warn(
      {
        taskEventId: current.taskEventId,
        heldContactId: current.originatorContactId,
        ignoredContactId: next.originatorContactId,
      },
      'turn-lanes: ignored a second holder stamp with a different originator',
    );
  }

  private laneHeldBy(taskEventId: string): Lane | undefined {
    return this.findHeld(taskEventId)?.lane;
  }

  private findHeld(taskEventId: string): { conversationId: string; lane: Lane } | undefined {
    for (const [conversationId, lane] of this.lanes) {
      if (lane.holder?.taskEventId === taskEventId) return { conversationId, lane };
    }
    return undefined;
  }

  private findWaiting(taskEventId: string): { conversationId: string; lane: Lane; waiter: Waiter } | undefined {
    for (const [conversationId, lane] of this.lanes) {
      const waiter = lane.waiters.find((item) => item.holder.taskEventId === taskEventId && !item.settled);
      if (waiter) return { conversationId, lane, waiter };
    }
    return undefined;
  }
}
