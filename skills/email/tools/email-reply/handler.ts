const MAX_BODY_LENGTH = 50000;

/**
 * Turn an explicit cc list into addresses (#2131). An address passes through; a
 * reference resolves through the gateway, the same resolver Gate C and the
 * approval display use. The first entry that is neither, or that does not
 * resolve, refuses the whole reply: a dropped cc would send to fewer people than
 * asked and report success.
 */
async function resolveCcList(
  gateway: OutboundGateway,
  raw: string,
  log: ToolContext['log'],
): Promise<{ cc: string } | { error: string }> {
  const addresses: string[] = [];
  for (const entry of raw.split(',').map((s) => s.trim()).filter((s) => s.length > 0)) {
    const shapeError = addressOrReferenceError(entry, 'email', 'cc');
    if (shapeError) return { error: shapeError };
    if (parseRecipientReference(entry) === null) {
      addresses.push(entry);
      continue;
    }
    const resolved = await gateway.resolveRecipientReference('email', entry, { field: 'cc' });
    if (!resolved.ok) return { error: resolved.error };
    if (!isSendableIdentifier('email', resolved.identifier)) {
      // The resolver only returns sendable identities; this guards a future change to it.
      log.warn({ field: 'cc' }, 'email-reply: verified email identity is not a valid address — refusing (#2131)');
      return { error: "The cc contact's verified email identity is not a valid address, so nothing was sent. It needs correcting in Contacts." };
    }
    // A reference that names an address already listed adds nothing.
    const key = resolved.identifier.toLowerCase();
    if (!addresses.some((addr) => addr.toLowerCase() === key)) addresses.push(resolved.identifier);
  }
  return { cc: addresses.join(', ') };
}

export class EmailReplyHandler implements ToolHandler {
  async execute(ctx: ToolContext): Promise<ToolResult> {
    const input = ctx.input as {
      body?: string;
      cc?: string;
      attachments?: unknown;
      context_bridge?: string;
    };
    const { body, cc: ccInput, attachments: attachmentsRaw, context_bridge: contextBridgeRaw } = input;
    // Same normalizers Gate C uses, so the fetch cache key cannot diverge (#1832).
    const replyToMessageId = replyToMessageIdFromInput(ctx.input);
    const accountId = emailAccountIdFromInput(ctx.input);

    const attachmentsParsed = parseAttachmentInputs(attachmentsRaw);
    if (typeof attachmentsParsed === 'string') {
      return { success: false, error: attachmentsParsed };
    }

    if (!replyToMessageId) {
      return { success: false, error: 'Missing required input: reply_to_message_id (string)' };
    }
    if (!body || typeof body !== 'string') {
      return { success: false, error: 'Missing required input: body (string)' };
    }

    if (body.length > MAX_BODY_LENGTH) {
      return { success: false, error: `body must be ${MAX_BODY_LENGTH} characters or fewer` };
    }

    // Defense in depth (#1817): Gate C's resolveEmailReplyRecipients also rejects
    // this shape before fetchMessage. Keep the check here so principal-bypass /
    // non-Gate-C paths still get the actionable error without a Nylas round-trip.
    if (looksLikeOutboundContextEntryId(replyToMessageId)) {
      return {
        success: false,
        error: replyToMessageIdLooksLikeEntryIdError(),
      };
    }
    const idError = validateNylasMessageId(replyToMessageId, 'reply_to_message_id');
    if (idError) {
      return { success: false, error: idError, errorType: 'VALIDATION_ERROR' };
    }

    if (!ctx.outboundGateway) {
      return {
        success: false,
        error: 'email-reply skill requires outboundGateway access. Declare "outboundGateway" in capabilities.',
      };
    }

    // Resolve cc before the thread fetch, so a bad entry costs no Nylas round trip.
    let ccResolved: unknown = ccInput;
    if (typeof ccInput === 'string' && ccInput.trim().length > 0) {
      const cc = await resolveCcList(ctx.outboundGateway, ccInput, ctx.log);
      if ('error' in cc) return { success: false, error: cc.error };
      ccResolved = cc.cc;
    }

    ctx.log.info({ replyToMessageId, accountId }, 'Replying to email via gateway');

    try {
      const original = await ctx.outboundGateway.getEmailMessage(replyToMessageId, accountId);

      const originalFrom = original.from[0]?.email;
      if (!originalFrom) {
        return {
          success: false,
          error: `Original message ${replyToMessageId} has no sender address — cannot reply`,
        };
      }

      // Defense in depth (#1734): relay suppress alone is not enough — Gate C can
      // still allow email-reply to the machine sender. Block that recipient only;
      // escalation to the principal (other recipients / channels) stays open.
      const autoGenBlock = autoGeneratedSenderBlockReason(ctx.taskMetadata, originalFrom);
      if (autoGenBlock) {
        return { success: false, error: autoGenBlock };
      }

      const baseSubject = original.subject.replace(/^Re:\s*/i, '');
      const replySubject = `Re: ${baseSubject}`;

      const ownedMailboxes = (ctx.selfEmails && ctx.selfEmails.length > 0)
        ? ctx.selfEmails
        : (ctx.selfEmail ? [ctx.selfEmail] : []);
      if (ccInput === undefined && ownedMailboxes.length === 0) {
        ctx.log.warn({ replyToMessageId }, 'email-reply: selfEmail not configured — Curia may CC itself in reply-all');
      }

      const recipientSet = deriveEmailReplyRecipientSet({
        originalFrom,
        originalTo: original.to,
        originalCc: original.cc,
        ccInput: ccResolved,
        selfEmails: ownedMailboxes,
      });
      if (!recipientSet) {
        return {
          success: false,
          error: 'Could not resolve reply recipients — original sender missing or cc is not a string',
        };
      }
      const ccAddresses = recipientSet.cc.length > 0 ? recipientSet.cc : undefined;

      // Append the quoted original message below the reply body. Formatting is
      // non-fatal — a quote failure must not block the reply from being sent.
      // htmlQuote is passed separately so it is appended after markdownToHtml(body)
      // in the gateway, preventing the HTML from being re-escaped.
      let htmlQuote: string | undefined;
      try {
        const candidate = buildReplyQuote(original, ctx.timezone, { format: 'html' });
        // Skip the quote silently if it would push the body past the size limit
        // (the agent-authored body already passed the guard above; a long thread
        // could tip the combined total over). The reply still goes out unquoted.
        htmlQuote = body.length + candidate.length <= MAX_BODY_LENGTH ? candidate : undefined;
      } catch (err) {
        ctx.log.warn(
          { err, replyToMessageId },
          'email-reply: buildReplyQuote failed (HTML stripping or date formatting) — sending without quote',
        );
      }

      // To is original.from. Pass email_participant only when that address is not
      // an owned mailbox and the receiving provider's Authentication-Results
      // shows SPF, DKIM, and DMARC all passing. A header the sender wrote does
      // not count. Otherwise omit the option and the gateway records an
      // unverified outbound_recipient (#2071). The gateway cannot infer this
      // from replyToMessageId: email-send sets that field too.
      const provenance = replyRecipientSource({
        addressFromHeader: true,
        recipient: originalFrom,
        selfEmails: ownedMailboxes,
        headers: original.headers,
      });
      const fromName = provenance ? replyDisplayName(original.from[0]?.name, originalFrom) : undefined;

      const result = await ctx.outboundGateway.send({
        channel: 'email',
        to: originalFrom,
        subject: replySubject,
        body,
        replyToMessageId,
        htmlQuote,
        ...(accountId ? { accountId } : {}),
        ...(ccAddresses ? { cc: ccAddresses } : {}),
        ...(attachmentsParsed.length > 0 ? { attachments: attachmentsParsed } : {}),
      }, {
        taskEventId: ctx.taskEventId,
        conversationId: ctx.conversationId,
        humanApproved: ctx.humanApproved,
        principalDirected: isPrincipalDirectedSend(ctx),
        ...(provenance ? { recipientSource: provenance } : {}),
        ...(fromName ? { recipientDisplayName: fromName } : {}),
        ...(attachmentsParsed.length > 0
          ? {
            reExecRecipe: {
              toolName: 'email-reply',
              partialPayload: ctx.input,
              description: `Send email reply with ${attachmentsParsed.length} attachment(s)`,
            },
            exportContext: {
              toolName: 'email-reply',
              agentId: ctx.agentId,
              exportItems: (ctx.input as Record<string, unknown>)['export_items'],
            },
          }
          : {}),
      });

      if (!result.success) {
        return { success: false, error: result.blockedReason ?? 'Email reply failed' };
      }

      // Register outbound context entry (best-effort, always fires).
      // Pass the agent-authored body only — not quotedBody — so outbound context stores
      // the meaningful reply content without the formatting-only quote block.
      await registerOutboundContext(ctx.outboundContext, contextBridgeRaw, {
        channelId: 'email',
        content: body,
        agentId: ctx.agentId ?? 'coordinator',
        log: ctx.log,
        boundTask: boundTaskFromMetadata(ctx.taskMetadata as Record<string, unknown> | undefined),
      });

      ctx.log.info(
        { messageId: result.messageId, to: originalFrom, subject: replySubject, cc: ccAddresses },
        'Email reply sent successfully',
      );

      return {
        success: true,
        data: {
          message_id: result.messageId,
          to: originalFrom,
          subject: replySubject,
          // Return the CC list that was used; empty string when none.
          cc: ccAddresses?.join(', ') ?? '',
        },
      };
    } catch (err) {
      if (err instanceof UnknownEmailAccountError) {
        ctx.log.error({ err, replyToMessageId, accountId }, 'Failed to reply to email');
        return { success: false, error: err.message };
      }
      ctx.log.error({ err, replyToMessageId }, 'Failed to reply to email');
      return { success: false, ...nylasMessageFailure(err, replyToMessageId, 'Failed to reply to email') };
    }
  }
}
