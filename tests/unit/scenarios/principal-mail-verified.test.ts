// The principal's own mail passes SPF, DKIM and DMARC, so a scenario's principal email is verified
// unless the case says `sender_verified: false` (GHSA-p49r-jqh2-v668): an unverified principal
// email carries none of the principal's authority, which would silently change every principal
// email case that never set the flag.
import { describe, expect, it } from 'vitest';
import { inboundNylasMessage, inboundSenderVerified } from '../../scenarios/harness.js';

describe('inboundSenderVerified', () => {
  it('defaults principal email to verified, and a delegate serving the principal', () => {
    expect(inboundSenderVerified({ from: 'principal' })).toBe(true);
    expect(inboundSenderVerified({ from: 'delegate' })).toBe(true);
    expect(inboundSenderVerified({ from: 'delegate', requester: 'principal' })).toBe(true);
  });

  it('keeps what the case says', () => {
    expect(inboundSenderVerified({ from: 'principal', email: { autoGenerated: false, autoGeneratedSignals: [], senderVerified: false } })).toBe(false);
    expect(inboundSenderVerified({ from: 'dana', email: { autoGenerated: false, autoGeneratedSignals: [], senderVerified: true } })).toBe(true);
  });

  it('leaves anyone else unset', () => {
    expect(inboundSenderVerified({ from: 'dana' })).toBeUndefined();
    expect(inboundSenderVerified({ from: 'delegate', requester: 'dana' })).toBeUndefined();
  });

  it("the fake mailbox's Authentication-Results agree with it", () => {
    const header = (from: string) => JSON.stringify(inboundNylasMessage('m-1', 'ceo@example.test', { from, content: 'hi' }, undefined).headers);
    expect(header('principal')).toContain('dmarc=pass');
    expect(header('dana')).toContain('dmarc=fail');
  });
});
