// Hand-off recovery (#2588): a passed-on or held correction that did not reach the work is
// re-run as a synthetic coordinator turn on the handing conversation, as that person, with
// liveTurn absent and the person's text scrubbed of sign-in codes. Modelled on the
// late-delegation wake, and laned like every synthetic turn.

import { describe, it, expect, vi } from 'vitest';
import pino from 'pino';
import {
  HandoffRecoveryPublisher,
  deterministicRecoveryEventId,
  handoffRecoveryContent,
} from '../../../src/agents/handoff-recovery.js';
import { handingIneligibility, handoffInboundEventId } from '../../../src/agents/turn-handoff.js';
import { EventBus } from '../../../src/bus/bus.js';
import type { AgentTaskEvent } from '../../../src/bus/events.js';
import {
  TurnActivityRegistry,
  isAuthenticatedRoot,
  TURN_ACTIVITY_WINDOW_MS,
  MAX_RUNNING_ROOT_AGE_MS,
  type HandoffRecoveryRequest,
  type RootTurn,
  type TaskStartInput,
} from '../../../src/dispatch/turn-activity.js';
import { TurnLanes } from '../../../src/dispatch/turn-lanes.js';
import type { InjectableInput } from '../../../src/dispatch/turn-lanes.js';
import { isUuid } from '../../../src/util/uuid.js';

const CONTACT = 'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa';
const HANDING_CONVERSATION = 'signal:+15550001';
const REQUEST = 'actually make it Tuesday, code 482913';
const ORIGINATOR = {
  contactId: CONTACT, channel: 'signal', systemRole: 'principal', tier: 'principal',
  initiatedAt: '2026-11-14T15:00:00.000Z', authenticated: true,
};
const quiet = pino({ level: 'silent' });
const scrub = (text: string) => text.replace('482913', '[sign-in code]');

function startTask(registry: TurnActivityRegistry, over: Partial<TaskStartInput> & { taskEventId: string }): void {
  registry.taskStarted({
    agentId: 'coordinator',
    conversationId: `conv-${over.taskEventId}`,
    channelId: 'sms',
    parentEventId: undefined,
    metadata: undefined,
    startedAt: Date.now(),
    originatorContactId: CONTACT,
    originatorResolved: true,
    originatorIsSystem: false,
    ...over,
  });
}

function startHanding(registry: TurnActivityRegistry): RootTurn {
  startTask(registry, {
    taskEventId: 'mine',
    channelId: 'signal',
    conversationId: HANDING_CONVERSATION,
    senderId: '+15550001',
    metadata: { originator: ORIGINATOR, inboundSenderText: REQUEST, inboundScanFindingCount: 0 },
  });
  return registry.rootOf('mine')!;
}

function input(): InjectableInput {
  return {
    inboundEventId: handoffInboundEventId('mine', 'other-root'),
    senderContactId: CONTACT,
    senderResolved: true,
    autoGenerated: false,
    injectionFindingCount: 0,
    channelId: 'signal',
    liveTurn: false,
    content: REQUEST,
    originalContent: REQUEST,
    receivedAt: '2026-11-14T15:00:00.000Z',
  };
}

function capture() {
  const bus = new EventBus(quiet);
  const tasks: AgentTaskEvent[] = [];
  const publish = vi.spyOn(bus, 'publish');
  bus.subscribe('agent.task', 'agent', (e) => { tasks.push(e as AgentTaskEvent); });
  const registerRouting = vi.fn();
  const publisher = new HandoffRecoveryPublisher({ bus, logger: quiet, scrubText: scrub, registerRouting });
  return { bus, tasks, publish, registerRouting, publisher };
}

/** The checks every trigger's recovery task must pass. */
function expectRecoveryTask(task: AgentTaskEvent, reason: HandoffRecoveryRequest['reason']): void {
  expect(task.payload).toMatchObject({
    agentId: 'coordinator',
    conversationId: HANDING_CONVERSATION,
    channelId: 'signal',
    senderId: '+15550001',
    syntheticTurn: true,
  });
  expect(task.payload.liveTurn).toBeUndefined();
  expect(task.payload.metadata).toMatchObject({
    originator: ORIGINATOR,
    wakeContext: expect.objectContaining({ derived: true }),
    handoffRecovery: { targetRootId: 'other-root', reason },
  });
  expect(task.payload.content).toContain("Earlier you passed this message on to another turn, but it didn't reach that work");
  expect(task.payload.content).toContain('Handle it here now: check what the other turn did and adjust rather than repeat it.');
  expect(task.payload.content).toContain('actually make it Tuesday, code [sign-in code]');
  expect(task.payload.content).not.toContain('482913');
  expect(task.parentEventId).toBe('mine');
  expect(isUuid(task.id)).toBe(true);
}

describe('HandoffRecoveryPublisher', () => {
  it('publishes a synthetic coordinator task on the handing conversation, routing first, on the system layer', async () => {
    const { tasks, publish, registerRouting, publisher } = capture();
    const registry = new TurnActivityRegistry({ logger: quiet });
    const from = startHanding(registry);
    publisher.recover({ from, targetRootId: 'other-root', input: input(), reason: 'returned' });
    await vi.waitFor(() => expect(tasks).toHaveLength(1));
    const task = tasks[0]!;
    expectRecoveryTask(task, 'returned');
    expect(task.id).toBe(deterministicRecoveryEventId(input().inboundEventId));
    expect(publish).toHaveBeenCalledWith('system', task);
    expect(registerRouting).toHaveBeenCalledWith(task.id, {
      channelId: 'signal', conversationId: HANDING_CONVERSATION, senderId: '+15550001', originator: ORIGINATOR,
    });
    expect(registerRouting.mock.invocationCallOrder[0]!).toBeLessThan(publish.mock.invocationCallOrder[0]!);
    // It goes through the lanes like every synthetic turn.
    const lanes = new TurnLanes({ enabled: true, maxInjectionsPerTurn: 2, extraRoundsPerInjection: 2, laneWaitTimeoutMs: 1_000, logger: quiet });
    expect(lanes.isLaned(task.payload)).toBe(true);
  });

  it("the recovery turn's root carries the handing root's channel authentication", async () => {
    const { tasks, publisher } = capture();
    const registry = new TurnActivityRegistry({ logger: quiet });
    const from = startHanding(registry);
    expect(isAuthenticatedRoot(from)).toBe(true);
    publisher.recover({ from, targetRootId: 'other-root', input: input(), reason: 'returned' });
    await vi.waitFor(() => expect(tasks).toHaveLength(1));
    const task = tasks[0]!;
    // Registered the way the runtime registers every task: from the task's own metadata.
    startTask(registry, {
      taskEventId: task.id,
      channelId: task.payload.channelId,
      conversationId: task.payload.conversationId,
      parentEventId: task.parentEventId,
      metadata: task.payload.metadata as Record<string, unknown>,
      senderId: task.payload.senderId,
    });
    const root = registry.rootOf(task.id)!;
    expect(root.rootId).toBe(task.id);
    expect(root.originatorAuthenticated).toBe(true);
    // So it reads the other-turns note, but still cannot hand off: it has no stamped text.
    expect(isAuthenticatedRoot(root)).toBe(true);
    expect(handingIneligibility(root, task.id)).toBe('no_request_text');
  });

  it('publishes one recovery per correction, however many triggers fire', async () => {
    const { tasks, publisher } = capture();
    const registry = new TurnActivityRegistry({ logger: quiet });
    const from = startHanding(registry);
    publisher.recover({ from, targetRootId: 'other-root', input: input(), reason: 'unresolved' });
    publisher.recover({ from, targetRootId: 'other-root', input: input(), reason: 'returned' });
    await vi.waitFor(() => expect(tasks).toHaveLength(1));
    await new Promise((r) => setTimeout(r, 10));
    expect(tasks).toHaveLength(1);
  });

  it('never throws: a handing turn with no originator is logged and skipped', async () => {
    const error = vi.fn();
    const logger = { error, warn: vi.fn(), info: vi.fn(), debug: vi.fn() } as unknown as typeof quiet;
    const bus = new EventBus(quiet);
    const publish = vi.spyOn(bus, 'publish');
    const publisher = new HandoffRecoveryPublisher({ bus, logger });
    const registry = new TurnActivityRegistry({ logger: quiet });
    startTask(registry, { taskEventId: 'bare', channelId: 'signal', conversationId: HANDING_CONVERSATION });
    expect(() => publisher.recover({ from: registry.rootOf('bare')!, targetRootId: 'x', input: input(), reason: 'returned' })).not.toThrow();
    await vi.waitFor(() => expect(error).toHaveBeenCalled());
    expect(publish).not.toHaveBeenCalled();
  });

  it('a handing turn whose sender was not authenticated is never re-run (defence in depth)', async () => {
    const error = vi.fn();
    const logger = { error, warn: vi.fn(), info: vi.fn(), debug: vi.fn() } as unknown as typeof quiet;
    const bus = new EventBus(quiet);
    const publish = vi.spyOn(bus, 'publish');
    const registerRouting = vi.fn();
    const publisher = new HandoffRecoveryPublisher({ bus, logger, registerRouting });
    const registry = new TurnActivityRegistry({ logger: quiet });
    // A forged email From resolved to the principal: performHandoff never hands from it.
    startTask(registry, {
      taskEventId: 'forged',
      channelId: 'email',
      conversationId: 'email:thread-1',
      senderId: 'ceo@example.com',
      metadata: { originator: { ...ORIGINATOR, channel: 'email', authenticated: false }, inboundSenderText: REQUEST, inboundScanFindingCount: 0 },
    });
    const from = registry.rootOf('forged')!;
    expect(isAuthenticatedRoot(from)).toBe(false);
    publisher.recover({ from, targetRootId: 'other-root', input: input(), reason: 'returned' });
    await vi.waitFor(() => expect(error).toHaveBeenCalledWith(
      expect.objectContaining({ fromRootId: 'forged' }),
      expect.stringContaining('not authenticated'),
    ));
    expect(publish).not.toHaveBeenCalled();
    expect(registerRouting).not.toHaveBeenCalled();
  });

  it('a publish that keeps failing is retried a bounded number of times, then logged at error, never thrown', async () => {
    const error = vi.fn();
    const warn = vi.fn();
    const logger = { error, warn, info: vi.fn(), debug: vi.fn() } as unknown as typeof quiet;
    const bus = new EventBus(quiet);
    const publish = vi.spyOn(bus, 'publish').mockRejectedValue(new Error('bus down'));
    const publisher = new HandoffRecoveryPublisher({ bus, logger, registerRouting: vi.fn(), retryDelaysMs: [0, 0] });
    const registry = new TurnActivityRegistry({ logger: quiet });
    const from = startHanding(registry);
    publisher.recover({ from, targetRootId: 'other-root', input: input(), reason: 'returned' });
    await vi.waitFor(() => expect(error).toHaveBeenCalledWith(
      expect.objectContaining({ reason: 'returned', attempts: 3 }),
      expect.stringContaining('lost'),
    ));
    expect(publish).toHaveBeenCalledTimes(3);
    expect(warn).toHaveBeenCalledTimes(2);
    expect(error).toHaveBeenCalledTimes(1);
    // Never more than the bound.
    await new Promise((r) => setTimeout(r, 20));
    expect(publish).toHaveBeenCalledTimes(3);
    // The id was released: a later trigger for the same correction may try again.
    publish.mockReset();
    publisher.recover({ from, targetRootId: 'other-root', input: input(), reason: 'unresolved' });
    await vi.waitFor(() => expect(publish).toHaveBeenCalled());
  });

  it('a transient publish failure is retried and the correction is re-run once', async () => {
    const { bus, tasks, publish } = capture();
    const warn = vi.fn();
    const error = vi.fn();
    const logger = { error, warn, info: vi.fn(), debug: vi.fn() } as unknown as typeof quiet;
    const publisher = new HandoffRecoveryPublisher({ bus, logger, scrubText: scrub, registerRouting: vi.fn(), retryDelaysMs: [0, 0] });
    publish.mockRejectedValueOnce(new Error('audit write failed'));
    const registry = new TurnActivityRegistry({ logger: quiet });
    const from = startHanding(registry);
    publisher.recover({ from, targetRootId: 'other-root', input: input(), reason: 'returned' });
    await vi.waitFor(() => expect(tasks).toHaveLength(1));
    expect(publish).toHaveBeenCalledTimes(2);
    expect(warn).toHaveBeenCalledWith(expect.objectContaining({ attempt: 1, retryInMs: 0 }), expect.stringContaining('retrying'));
    expect(error).not.toHaveBeenCalled();
    expectRecoveryTask(tasks[0]!, 'returned');
  });

  it('a second trigger while a retry is pending does not publish again', async () => {
    const { bus, tasks, publish } = capture();
    const publisher = new HandoffRecoveryPublisher({ bus, logger: quiet, scrubText: scrub, registerRouting: vi.fn(), retryDelaysMs: [200] });
    publish.mockRejectedValueOnce(new Error('audit write failed'));
    const registry = new TurnActivityRegistry({ logger: quiet });
    const from = startHanding(registry);
    publisher.recover({ from, targetRootId: 'other-root', input: input(), reason: 'unresolved' });
    await vi.waitFor(() => expect(publish).toHaveBeenCalledTimes(1), { interval: 5 });
    publisher.recover({ from, targetRootId: 'other-root', input: input(), reason: 'returned' });
    await vi.waitFor(() => expect(tasks).toHaveLength(1));
    await new Promise((r) => setTimeout(r, 50));
    expect(publish).toHaveBeenCalledTimes(2);
    expect(tasks).toHaveLength(1);
  });

  it('an email handing turn: the reply leaves from its account, and its audience is judged the same', async () => {
    const { tasks, registerRouting, publisher } = capture();
    const selfEmails = ['curia@example.com'];
    const registry = new TurnActivityRegistry({ logger: quiet, selfEmails });
    const emailOriginator = { ...ORIGINATOR, channel: 'email' };
    startTask(registry, {
      taskEventId: 'mine-email',
      channelId: 'email',
      conversationId: 'email:thread-1',
      senderId: 'ada@example.com',
      accountId: 'assistant-2',
      metadata: {
        originator: emailOriginator,
        inboundSenderText: REQUEST,
        inboundScanFindingCount: 0,
        curiaRole: 'to',
        primaryRecipientEmails: [],
        participants: [
          { email: 'ada@example.com', role: 'from', name: 'Ada' },
          { email: 'curia@example.com', role: 'to' },
        ],
        // Not an audience input: it must not ride along.
        nylasThreadId: 'thread-1',
      },
    });
    const from = registry.rootOf('mine-email')!;
    expect(from.audienceOneToOne).toBe(true);
    expect(from.accountId).toBe('assistant-2');
    publisher.recover({ from, targetRootId: 'other-root', input: input(), reason: 'returned' });
    await vi.waitFor(() => expect(tasks).toHaveLength(1));
    const task = tasks[0]!;
    expect(task.payload.accountId).toBe('assistant-2');
    expect(registerRouting).toHaveBeenCalledWith(task.id, expect.objectContaining({
      channelId: 'email', conversationId: 'email:thread-1', senderId: 'ada@example.com', accountId: 'assistant-2',
    }));
    const metadata = task.payload.metadata as Record<string, unknown>;
    expect(metadata['nylasThreadId']).toBeUndefined();
    expect(metadata['participants']).toEqual([
      { email: 'ada@example.com', role: 'from' },
      { email: 'curia@example.com', role: 'to' },
    ]);
    // Registered the way the runtime registers every task: the same audience, by the same rule.
    startTask(registry, {
      taskEventId: task.id,
      channelId: task.payload.channelId,
      conversationId: task.payload.conversationId,
      parentEventId: task.parentEventId,
      metadata,
      senderId: task.payload.senderId,
    });
    expect(registry.rootOf(task.id)!.audienceOneToOne).toBe(true);
  });

  it("a cc'd email handing turn's recovery is not one-to-one either", async () => {
    const { tasks, publisher } = capture();
    const selfEmails = ['curia@example.com'];
    const registry = new TurnActivityRegistry({ logger: quiet, selfEmails });
    startTask(registry, {
      taskEventId: 'mine-cc',
      channelId: 'email',
      conversationId: 'email:thread-2',
      senderId: 'ada@example.com',
      metadata: {
        originator: { ...ORIGINATOR, channel: 'email' },
        curiaRole: 'cc',
        primaryRecipientEmails: ['bob@example.com'],
        participants: [{ email: 'ada@example.com', role: 'from' }, { email: 'curia@example.com', role: 'cc' }],
      },
    });
    const from = registry.rootOf('mine-cc')!;
    expect(from.audienceOneToOne).toBe(false);
    expect(from.accountId).toBeNull();
    publisher.recover({ from, targetRootId: 'other-root', input: input(), reason: 'returned' });
    await vi.waitFor(() => expect(tasks).toHaveLength(1));
    const task = tasks[0]!;
    expect(task.payload.accountId).toBeUndefined();
    startTask(registry, {
      taskEventId: task.id,
      channelId: 'email',
      conversationId: 'email:thread-2',
      parentEventId: task.parentEventId,
      metadata: task.payload.metadata as Record<string, unknown>,
    });
    expect(registry.rootOf(task.id)!.audienceOneToOne).toBe(false);
  });

  it('content is the preamble, then the text', () => {
    expect(handoffRecoveryContent('root_ended', 'hi')).toMatch(/^Earlier you passed this message on to another turn, but it didn't reach that work \([^)]+\)\. Handle it here now: check what the other turn did and adjust rather than repeat it\.\n\nhi$/);
  });
});

describe('registry triggers reach the publisher (#2588)', () => {
  it('(c) a root ending with a held correction publishes the recovery task', async () => {
    const { tasks, publisher } = capture();
    const registry = new TurnActivityRegistry({ logger: quiet, recoverHandoff: publisher.recover });
    const from = startHanding(registry);
    startTask(registry, { taskEventId: 'other-root', conversationId: 'sms:+15550001' });
    registry.holdForWake('other-root', input(), from);
    registry.taskEnded('other-root');
    await vi.waitFor(() => expect(tasks).toHaveLength(1));
    expectRecoveryTask(tasks[0]!, 'root_ended');
  });

  it('(d) a root dropped with a held correction publishes the recovery task', async () => {
    const { tasks, publisher } = capture();
    let t = Date.now();
    const registry = new TurnActivityRegistry({ logger: quiet, now: () => t, recoverHandoff: publisher.recover });
    const from = startHanding(registry);
    startTask(registry, { taskEventId: 'other-root', conversationId: 'sms:+15550001', startedAt: t });
    registry.holdForWake('other-root', input(), from);
    t += MAX_RUNNING_ROOT_AGE_MS + 3 * TURN_ACTIVITY_WINDOW_MS;
    startTask(registry, { taskEventId: 'later', startedAt: t });
    await vi.waitFor(() => expect(tasks).toHaveLength(1));
    expectRecoveryTask(tasks[0]!, 'root_dropped');
  });

  it('(a), (b) and (e) requests map to the same task shape', async () => {
    for (const reason of ['returned', 'unresolved', 'wake_not_injected', 'wake_returned'] as const) {
      const { tasks, publisher } = capture();
      const registry = new TurnActivityRegistry({ logger: quiet });
      const from = startHanding(registry);
      publisher.recover({ from, targetRootId: 'other-root', input: input(), reason });
      await vi.waitFor(() => expect(tasks).toHaveLength(1));
      expectRecoveryTask(tasks[0]!, reason);
    }
  });
});
