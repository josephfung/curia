// Trigger detection for the coordinator's per-turn guidance (#1959): each key is present
// when its trigger is and absent otherwise.

import { describe, expect, it } from 'vitest';
import {
  hasBookingPageLink,
  inboundTurnGuidance,
  looksLikeForward,
  looksLikeMakeRoom,
  looksLikeSpotCheckReply,
  parseSpotCheckVerdicts,
  spotCheckCandidateText,
  type InboundGuidanceFacts,
} from '../../../src/dispatch/turn-guidance-triggers.js';
import { htmlToText } from '../../../src/channels/email/html-to-text.js';

function facts(overrides: Partial<InboundGuidanceFacts> = {}): InboundGuidanceFacts {
  return {
    liveTurn: true,
    injectedEntryMetadata: [],
    channelId: 'signal',
    curiaCc: false,
    autoGeneratedSuppress: false,
    verificationCodeReceived: false,
    spotCheckReply: false,
    ...overrides,
  };
}

const TASK_WAKE = { bind_reply: true, task_id: '3804c301-aaaa-4bbb-8ccc-dddddddddddd' };

describe('inboundTurnGuidance', () => {
  it('principal turn with no outbound block gets only the reply-shaped note', () => {
    expect(inboundTurnGuidance(facts())).toEqual(['principal-reply-shaped']);
  });

  it('principal turn with the block gets the block guidance instead of the note', () => {
    const keys = inboundTurnGuidance(facts({ injectedEntryMetadata: [null] }));
    expect(keys).toEqual(['outbound-context']);
  });

  it('non-principal turn gets the non-principal guidance, never the block guidance', () => {
    expect(inboundTurnGuidance(facts({ liveTurn: false }))).toEqual(['non-principal-reply-shaped']);
    // Entries never reach a non-principal turn, but even if a caller passed some, the
    // block guidance must not appear without the principal.
    const keys = inboundTurnGuidance(facts({ liveTurn: false, injectedEntryMetadata: [TASK_WAKE] }));
    expect(keys).toEqual(['non-principal-reply-shaped']);
  });

  it('non-principal turn with entries sent to the sender gets the recipient block guidance (#2261)', () => {
    expect(inboundTurnGuidance(facts({ liveTurn: false, recipientEntryCount: 1 })))
      .toEqual(['non-principal-reply-shaped', 'recipient-outbound-context']);
    // Never on a principal turn, which has its own block guidance.
    expect(inboundTurnGuidance(facts({ recipientEntryCount: 1 }))).toEqual(['principal-reply-shaped']);
    // Machine mail gets nothing, block or not.
    expect(inboundTurnGuidance(facts({ liveTurn: false, recipientEntryCount: 1, autoGeneratedSuppress: true }))).toEqual([]);
  });

  describe('outbound-context sub-rules follow what the entries carry', () => {
    it.each([
      ['outbound-context-task-wake', TASK_WAKE],
      ['outbound-context-clarification', { resume_token: 'tok' }],
      ['outbound-context-debrief', { subject: 'Acme Q3 sync', eventId: 'evt-1' }],
    ] as const)('%s', (key, metadata) => {
      expect(inboundTurnGuidance(facts({ injectedEntryMetadata: [metadata] }))).toEqual([
        'outbound-context',
        key,
      ]);
      // An entry without that metadata does not trigger it.
      expect(inboundTurnGuidance(facts({ injectedEntryMetadata: [{ meeting: 'x' }] }))).not.toContain(key);
    });

    it('needs a task_id for the task-wake rule, and non-empty token and subject', () => {
      const keys = inboundTurnGuidance(facts({
        injectedEntryMetadata: [{ bind_reply: true }, { resume_token: '' }, { subject: '  ' }],
      }));
      expect(keys).toEqual(['outbound-context']);
    });

    it('collects every sub-rule present across entries', () => {
      const keys = inboundTurnGuidance(facts({
        injectedEntryMetadata: [TASK_WAKE, { resume_token: 'tok' }, { subject: 'Standup' }],
      }));
      expect(keys).toEqual([
        'outbound-context',
        'outbound-context-task-wake',
        'outbound-context-clarification',
        'outbound-context-debrief',
      ]);
    });
  });

  describe('email', () => {
    it('a direct email gets the direct-reply rule and the etiquette', () => {
      const keys = inboundTurnGuidance(facts({ channelId: 'email', liveTurn: false }));
      expect(keys).toEqual(['non-principal-reply-shaped', 'email-direct-reply', 'email-etiquette']);
    });

    it('a CC from the principal gets the CC judgment and CC reply mechanics, not the direct rule', () => {
      const keys = inboundTurnGuidance(facts({ channelId: 'email', curiaCc: true }));
      expect(keys).toEqual(['principal-reply-shaped', 'email-cc-principal', 'email-cc-reply', 'email-etiquette']);
    });

    it('a CC from someone else gets the CC reply mechanics without the principal judgment', () => {
      const keys = inboundTurnGuidance(facts({ channelId: 'email', curiaCc: true, liveTurn: false }));
      expect(keys).toContain('email-cc-reply');
      expect(keys).not.toContain('email-cc-principal');
      expect(keys).not.toContain('email-direct-reply');
    });

    it('a non-email turn gets no email guidance', () => {
      for (const channelId of ['signal', 'sms', 'slack', 'cli', 'http']) {
        expect(inboundTurnGuidance(facts({ channelId })).some((k) => k.startsWith('email-'))).toBe(false);
      }
    });
  });

  it('suppressed auto-generated mail gets nothing: its preamble already says NO_REPLY', () => {
    expect(inboundTurnGuidance(facts({ channelId: 'email', liveTurn: false, autoGeneratedSuppress: true }))).toEqual([]);
  });

  describe('verification-code-received (#2017)', () => {
    it('follows the reply-shaped note when the principal\'s message carried a tracked code', () => {
      expect(inboundTurnGuidance(facts({ verificationCodeReceived: true }))).toEqual([
        'principal-reply-shaped',
        'verification-code-received',
      ]);
      const email = inboundTurnGuidance(facts({ verificationCodeReceived: true, channelId: 'email' }));
      expect(email).toContain('verification-code-received');
    });

    it('is absent without a registered code, and never on a non-principal turn', () => {
      expect(inboundTurnGuidance(facts())).not.toContain('verification-code-received');
      expect(inboundTurnGuidance(facts({ liveTurn: false, verificationCodeReceived: true }))).not.toContain(
        'verification-code-received',
      );
    });
  });

  describe('spot-check verdict (record-spot-check)', () => {
    it('adds spot-check-reply on a live turn that looks like a verdict', () => {
      expect(inboundTurnGuidance(facts({ spotCheckReply: true }))).toContain('spot-check-reply');
    });

    // Review Focus 1: only a live principal turn may record a verdict.
    it('replaces principal-reply-shaped: a live verdict with no outbound block gets only spot-check-reply', () => {
      const keys = inboundTurnGuidance(facts({ spotCheckReply: true }));
      expect(keys).toEqual(['spot-check-reply']);
      expect(keys).not.toContain('principal-reply-shaped');
    });

    it('keeps the outbound-context keys and adds spot-check-reply alongside them', () => {
      expect(inboundTurnGuidance(facts({ spotCheckReply: true, injectedEntryMetadata: [TASK_WAKE] }))).toEqual([
        'outbound-context',
        'outbound-context-task-wake',
        'spot-check-reply',
      ]);
    });

    it('never adds spot-check-reply when the turn is not live, even if the text matches', () => {
      expect(inboundTurnGuidance(facts({ liveTurn: false, spotCheckReply: true }))).not.toContain('spot-check-reply');
      expect(
        inboundTurnGuidance(facts({ liveTurn: false, spotCheckReply: true, channelId: 'email' })),
      ).not.toContain('spot-check-reply');
    });

    // F1: a principal email where Curia is only CC'd ("2 good candidates came through") is
    // written to someone else, so it is never a verdict on Curia's digest.
    it("does not add it when Curia was only CC'd, and the reply-shaped note stays", () => {
      const keys = inboundTurnGuidance(facts({ channelId: 'email', curiaCc: true, spotCheckReply: true }));
      expect(keys).not.toContain('spot-check-reply');
      expect(keys).toEqual(['principal-reply-shaped', 'email-cc-principal', 'email-cc-reply', 'email-etiquette']);
    });

    it('does not add it when the text does not look like a verdict', () => {
      expect(inboundTurnGuidance(facts({ spotCheckReply: false }))).not.toContain('spot-check-reply');
    });

    it('is not added to suppressed auto-generated mail', () => {
      expect(
        inboundTurnGuidance(facts({ channelId: 'email', liveTurn: false, autoGeneratedSuppress: true, spotCheckReply: true })),
      ).toEqual([]);
    });
  });

  describe('principal-forward (#2227)', () => {
    it('replaces the reply-shaped note on a live principal email forward', () => {
      const keys = inboundTurnGuidance(facts({ channelId: 'email', forward: true }));
      expect(keys).toEqual(['principal-forward', 'email-direct-reply', 'email-etiquette']);
    });

    it('keeps the outbound-context keys alongside it', () => {
      const keys = inboundTurnGuidance(facts({ channelId: 'email', forward: true, injectedEntryMetadata: [null] }));
      expect(keys).toEqual(['principal-forward', 'outbound-context', 'email-direct-reply', 'email-etiquette']);
    });

    it("is never added on a non-principal turn, a CC, or a non-email channel", () => {
      expect(inboundTurnGuidance(facts({ channelId: 'email', forward: true, liveTurn: false }))).not.toContain('principal-forward');
      expect(inboundTurnGuidance(facts({ channelId: 'email', forward: true, curiaCc: true }))).toEqual([
        'principal-reply-shaped', 'email-cc-principal', 'email-cc-reply', 'email-etiquette',
      ]);
      expect(inboundTurnGuidance(facts({ forward: true }))).toEqual(['principal-reply-shaped']);
    });
  });
  describe('senders the principal knows (#2227)', () => {
    it('names the evidence, then the weighing rule, on a non-principal turn', () => {
      expect(inboundTurnGuidance(facts({ channelId: 'email', liveTurn: false, principalAcquaintance: 'principal-domain' }))).toEqual([
        'non-principal-reply-shaped', 'principal-colleague', 'acquaintance-time-request', 'email-direct-reply', 'email-etiquette',
      ]);
      expect(inboundTurnGuidance(facts({ channelId: 'email', liveTurn: false, principalAcquaintance: 'principal-correspondence' }))).toEqual([
        'non-principal-reply-shaped', 'principal-correspondent', 'acquaintance-time-request', 'email-direct-reply', 'email-etiquette',
      ]);
    });

    it('is never added on a principal turn', () => {
      expect(inboundTurnGuidance(facts({ principalAcquaintance: 'principal-domain' }))).toEqual(['principal-reply-shaped']);
    });
  });

  describe('booking-link (#2227)', () => {
    // Keys come back in detection order; renderTurnGuidance puts them in TURN_GUIDANCE_ORDER.
    it('is added on any sender, and beside the forward note', () => {
      expect(inboundTurnGuidance(facts({ channelId: 'email', bookingLink: true, liveTurn: false }))).toEqual([
        'non-principal-reply-shaped', 'booking-link', 'email-direct-reply', 'email-etiquette',
      ]);
      expect(inboundTurnGuidance(facts({ channelId: 'email', bookingLink: true, forward: true }))).toEqual([
        'principal-forward', 'booking-link', 'email-direct-reply', 'email-etiquette',
      ]);
    });

    it('is not added to suppressed auto-generated mail', () => {
      expect(inboundTurnGuidance(facts({ channelId: 'email', liveTurn: false, bookingLink: true, autoGeneratedSuppress: true }))).toEqual([]);
    });
  });
});

